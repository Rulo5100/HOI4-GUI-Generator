"""Project: everything one spec generates, and the files it becomes.

    p = Project(fs, prefix="XYZ", theme="steel")          # default file names from the prefix
    bar = p.sprite(Bar(p.gfx_name("bar"), p.png("bar"), 150, 14, "gold"))
    b = p.board("XYZ_board")
    ...
    p.write()                                             # or guigen.cli does it for you

Files (all mod-relative, override any of them in `files=`):

    gui           interface/<P>_guigen.gui
    gfx           interface/<P>_guigen.gfx
    scripted_gui  common/scripted_guis/<P>_guigen_guis.txt
    scripted_loc  common/scripted_localisation/<P>_guigen_loc.txt
    frames        common/scripted_effects/<P>_guigen_frames.txt   (None: not written)
    loc           localisation/english/<P>_guigen_l_english.yml
    png_dir       gfx/interface/<P>

loc_mode: "own" writes the whole yml, "merge" updates only our keys in an existing yml, "none" writes
nothing (use when another build owns the loc file; the validator still checks the keys).
"""
from .board import Board
from .frames import FrameSet
from .loc import DefinedText, Loc
from .sprites import GfxIndex, SpriteSet
from .theme import Theme


class Project:
    def __init__(self, fs, prefix, theme="manchukuo", files=None, loc_mode="own", language="english",
                 frame_effect="{P}_guigen_refresh_frames", sloc_header=None, frames_header=None):
        self.fs, self.prefix = fs, prefix
        self.theme = Theme.get(theme)
        P = prefix
        self.files = {
            "gui": f"interface/{P}_guigen.gui",
            "gfx": f"interface/{P}_guigen.gfx",
            "scripted_gui": f"common/scripted_guis/{P}_guigen_guis.txt",
            "scripted_loc": f"common/scripted_localisation/{P}_guigen_loc.txt",
            "frames": f"common/scripted_effects/{P}_guigen_frames.txt",
            "loc": f"localisation/{language}/{P}_guigen_l_{language}.yml",
            "png_dir": f"gfx/interface/{P}",
        }
        self.files.update(files or {})
        self.loc_mode, self.language = loc_mode, language
        self.frame_effect = frame_effect.replace("{P}", P)
        self.sloc_header = sloc_header if sloc_header is not None else f"# {P} scripted loc (generated by guigen)\n"
        self.frames_header = frames_header if frames_header is not None else f"# {P} GUI frame variables (generated by guigen)\n\n"
        self.sprites = SpriteSet()
        self.boards = []
        self.windows = []             # extra top-level windows (dynamic list entry templates)
        self.locs = Loc()
        self.defined_texts = []
        self.frames = FrameSet()
        self.embedded = []            # (file, block name, text): generated blocks that live in files we do not own
        self._gfx_index = None

    # ------------------------------------------------------------------ naming
    def png(self, stem):
        return f"{self.files['png_dir']}/{self.prefix}_{stem}.png"

    def gfx_name(self, stem):
        return f"GFX_{self.prefix}_{stem}"

    # ------------------------------------------------------------------ content
    def sprite(self, s):
        s.theme = self.theme
        return self.sprites.add(s)

    def statemap(self, smap):
        for s in smap.sprites():
            self.sprite(s)
        return smap

    def board(self, name, **kw):
        b = Board(self, name, **kw)
        self.boards.append(b)
        return b

    def window(self, w):
        self.windows.append(w)
        return w

    def loc(self, key, text):
        return self.locs.add(key, text)

    def defined_text(self, name, cases):
        dt = DefinedText(name, cases)
        for _, key, txt in dt.cases:
            if txt is not None:
                self.loc(key, txt)
        self.defined_texts.append(dt)
        return dt

    def frame(self, rule):
        return self.frames.add(rule)

    def embed(self, file, block, text):
        """Record a block that belongs in a file another build owns (checked by `guigen diff`)."""
        self.embedded.append((file, block, text))

    # ------------------------------------------------------------------ lookups
    @property
    def gfx_index(self):
        if self._gfx_index is None:
            self._gfx_index = GfxIndex(self.fs)
        return self._gfx_index

    def sprite_size(self, name):
        """(frame width, height) of a generated or existing sprite, or None."""
        s = self.sprites.get(name)
        if s:
            try:
                return s.frame_size
            except Exception:
                return None
        idx = self.gfx_index
        if name in idx:
            im = idx.open(name)
            if im is not None:
                return im.width // max(1, idx.frames(name) or 1), im.height
        return None

    # ------------------------------------------------------------------ output text
    def gui_text(self):
        return "guiTypes = {\n" + "".join(b.window.emit(1) for b in self.boards) + "".join(w.emit(1) for w in self.windows) + "}\n"

    def gfx_text(self):
        return self.sprites.gfx()

    def scripted_gui_text(self):
        return "scripted_gui = {\n" + "".join(b.scripted_gui() for b in self.boards) + "}\n"

    def scripted_loc_text(self):
        return self.sloc_header + "".join(dt.emit() for dt in self.defined_texts)

    def frames_text(self):
        return self.frames_header + self.frames.effect(self.frame_effect)

    def outputs(self):
        """[(mod-relative path, kind, payload, bom)] kind: text | image | loc."""
        f = self.files
        out = []
        if self.sprites.items:
            out.append((f["gfx"], "text", self.gfx_text(), False))
        if self.boards or self.windows:
            out.append((f["gui"], "text", self.gui_text(), False))
            out.append((f["scripted_gui"], "text", self.scripted_gui_text(), False))
        if self.defined_texts:
            out.append((f["scripted_loc"], "text", self.scripted_loc_text(), False))
        if self.frames.rules and f.get("frames"):
            out.append((f["frames"], "text", self.frames_text(), False))
        if self.locs.entries and self.loc_mode != "none":
            out.append((f["loc"], "loc", None, True))
        for s in self.sprites:
            out.append((s.texture, "image", s, False))
        return out

    def loc_text(self):
        if self.loc_mode == "merge" and self.fs.exists(self.files["loc"]):
            return self.locs.merge_into(self.fs.read_text(self.files["loc"])[0], self.language)
        return self.locs.yml(self.language)

    def write(self):
        """Write every output through self.fs (to the staging folder when the fs is staging)."""
        for rel, kind, payload, bom in self.outputs():
            if kind == "image":
                self.fs.write_image(rel, payload.image(self.theme))
            elif kind == "loc":
                self.fs.write_text(rel, self.loc_text(), bom=True, check_braces=False)
            else:
                self.fs.write_text(rel, payload, bom=bom)
        return self.fs.written
